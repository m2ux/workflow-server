"""Render Codex instructions, native permissions, MCP config, and hooks."""

import hashlib
import json
from functools import partial
from pathlib import Path
import shlex
import tomllib
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str((HERE / "shared").resolve()))
sys.path.insert(0, str((HERE.parent / "hooks/shared").resolve()))

from permissions import load_policy
from rendering import as_json, hook_group, rule_text


def codex_config(workspace: Path, home: Path, policy: dict, mcp: dict) -> str:
    # Literal Unicode avoids JSON surrogate escapes, which TOML rejects.
    quote = partial(json.dumps, ensure_ascii=False)
    parts = ["# Generated by scripts/render-harnesses.py.",
             f"developer_instructions = {quote(rule_text(workspace, home))}",
             "", "[sandbox_workspace_write]",
             f"writable_roots = {quote(policy['directories'])}", ""]
    for name, spec in mcp.get("mcpServers", {}).items():
        parts.append(f"[mcp_servers.{quote(name)}]")
        for key in ("command", "url", "args"):
            if key in spec:
                parts.append(f"{key} = {quote(spec[key])}")
        if spec.get("env"):
            parts.append(f"[mcp_servers.{quote(name)}.env]")
            parts.extend(f"{quote(key)} = {quote(str(value))}" for key, value in spec["env"].items())
        parts.append("")
    result = "\n".join(parts)
    tomllib.loads(result)
    return result



#: Codex discovers hooks through an installed plugin, so the workspace carries a
#: local marketplace of one. PLUGIN is its directory, relative to the workspace.
PLUGIN = ".codex/plugin"
PLUGIN_NAME = "workspace-command-policy"
MARKETPLACE_NAME = "workflow-server-workspace"


def plugin_manifest(version: str) -> dict:
    return {
        "name": PLUGIN_NAME,
        "version": version,
        "description": "Workspace command policy: blocking rules, confirmation requirements "
                       "and approval grants, shared with Claude Code and Cursor.",
        "interface": {
            "displayName": "Workspace Command Policy",
            "shortDescription": "One command policy across every harness.",
            "category": "Developer Tools",
        },
    }


def marketplace_manifest() -> dict:
    return {
        "name": MARKETPLACE_NAME,
        "interface": {"displayName": "Workflow Server Workspace"},
        "plugins": [{
            "name": PLUGIN_NAME,
            "source": {"source": "local", "path": f"./{PLUGIN}"},
            "policy": {"installation": "AVAILABLE"},
            "category": "Developer Tools",
        }],
    }


def plugin_version(hooks: dict) -> str:
    """A version the plugin cache keys on, so a changed registration reinstalls."""
    digest = hashlib.sha256(as_json(hooks).encode()).hexdigest()
    return f"0.1.{int(digest[:8], 16)}"


def render(workspace: Path, home: Path, mcp: dict | None = None) -> dict[str, str]:
    if mcp is None:
        config = workspace / ".codex/config.toml"
        if config.exists():
            mcp = {"mcpServers": tomllib.loads(config.read_text()).get("mcp_servers", {})}
        else:
            mcp = json.loads((workspace / ".mcp.json").read_text())
    command = f"python3 {shlex.quote(str(workspace / '.codex/hooks/adapter.py'))}"
    hooks = {"hooks": {
        "PreToolUse": [hook_group(command, "^Bash$")],
        "PermissionRequest": [hook_group(command, "^(Bash|mcp__.*)$")],
    }}
    return {
        ".codex/config.toml": codex_config(workspace, home, load_policy(workspace, home), mcp),
        f"{PLUGIN}/hooks/hooks.json": as_json(hooks),
        f"{PLUGIN}/.codex-plugin/plugin.json": as_json(plugin_manifest(plugin_version(hooks))),
        ".agents/plugins/marketplace.json": as_json(marketplace_manifest()),
    }
